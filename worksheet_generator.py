def render_shape_match(avoid_titles, difficulty):
    rows = {"easy": 3, "medium": 4, "hard": 5}[difficulty]
    shapes = pick_shapes(avoid_titles, rows)
    row_html = ""
    for shape in shapes:
        color_a = random.choice(COLORS)
        color_b = color_a if random.random() > 0.5 else random.choice([c for c in COLORS if c != color_a])
        cells = "".join(
            f'<div class="cell">{shape_svg(shape, color_a)}</div><div class="cell">{shape_svg(shape, color_b)}</div>'
        )
        row_html += f'<div class="match-row">{cells}<div class="answer-circle">SAME&nbsp;&nbsp;&nbsp;DIFFERENT</div></div>'
    instructions = "Look at each pair. Circle SAME if they match, or DIFFERENT if they don't."
    return instructions, f'<div class="grid">{row_html}</div>'


def render_big_trace(avoid_titles, difficulty):
    """2-3y/3-4y: pencil control for circles/lines, then imitating a
    variety of shapes. Big dashed outlines to trace, sized down slightly
    as difficulty rises (bigger target = easier for less control)."""
    count = {"easy": 2, "medium": 3, "hard": 4}[difficulty]
    size = {"easy": 170, "medium": 140, "hard": 120}[difficulty]
    shapes = pick_shapes(avoid_titles, count)
    items = ""
    for shape in shapes:
        raw = SHAPE_PATHS[shape].format(c="none")
        raw = raw.replace('stroke-width="5"', 'stroke-width="4" stroke-dasharray="9,5"')
        items += f'<div class="cell"><svg viewBox="0 0 120 120" width="{size}" height="{size}">{raw}</svg></div>'
    instructions = "Trace over each shape's dashed outline with a finger first, then with a crayon."
    return instructions, f'<div class="pattern-row">{items}</div>'


def render_count_aloud(avoid_titles, difficulty):
    """2-3y: 'begins to count with numbers' — verbal only, no writing
    skill yet, so no answer box, just objects to count together."""
    max_count = {"easy": 3, "medium": 4, "hard": 5}[difficulty]
    rows = 3
    shapes = pick_shapes(avoid_titles, rows)
    row_html = ""
    for shape in shapes:
        count = random.randint(2, max_count)
        color = random.choice(COLORS)
        icons = "".join(shape_svg(shape, color, size=55) for _ in range(count))
        row_html += f'<div class="count-row"><div class="icons">{icons}</div></div>'
    instructions = "Count each row together out loud. Ask: 'How many do you see?'"
    return instructions, f'<div class="grid">{row_html}</div>'


