def render_look_point(avoid_titles, difficulty):
    """0-1y: one giant, high-contrast shape for the educator to hold up and
    narrate. Not something baby completes — no writing, no fine motor
    demand at all, matching 'tracks slow moving object', 'looks at
    edges/patterns with light-dark contrast and faces'."""
    avoid_text = " ".join(avoid_titles).lower()
    choices = [s for s in SHAPE_NAMES if s not in avoid_text] or SHAPE_NAMES
    shape = random.choice(choices)
    color = random.choice(COLORS)
    big = f'<svg viewBox="0 0 120 120" width="360" height="360">{SHAPE_PATHS[shape].format(c=color)}</svg>'
    instructions = ("For the educator: hold this card about 20-30cm from baby's face. "
                     "Name the shape and color slowly, then pause so baby can look and study it.")
    return instructions, f'<div class="coloring-box">{big}</div>'


def render_point_and_name_shapes(avoid_titles, difficulty):
    """1-2y/2-3y: 'points to objects when named' / 'recognises and
    identifies common objects and pictures by pointing'. A reference card
    for the naming game, not a task the child fills in."""
    shapes = pick_shapes(avoid_titles, 3)
    items = ""
    for shape in shapes:
        color = random.choice(COLORS)
        items += (f'<div class="point-name-item">{shape_svg(shape, color, size=110)}'
                   f'<div class="point-name-label">{shape}</div></div>')
    instructions = "Say each shape's name out loud and ask your child to point to it."
    return instructions, f'<div class="point-name-row">{items}</div>'


def render_point_and_name_body(avoid_titles, difficulty):
    """1-2y: 'knows some body parts', 'points to body parts in a game'.
    No reading required — the word is printed only for the educator/parent."""
    avoid_text = " ".join(avoid_titles).lower()
    ordered = [p for p in BODY_PART_DIFFICULTY_ORDER if p not in avoid_text] or BODY_PART_DIFFICULTY_ORDER
    parts = ordered[:3]
    dots = ""
    labels = []
    for part in parts:
        x, y = BODY_PART_COORDS[part]
        dots += f'<circle cx="{x}" cy="{y}" r="10" fill="#FFD93D" stroke="#333" stroke-width="3"/>'
        labels.append(part)
    svg = f'<svg viewBox="0 0 300 320" width="260" height="280">{STICK_FIGURE_OUTLINE}{dots}</svg>'
    legend = "".join(f'<div class="legend-item">{p}</div>' for p in labels)
    instructions = "Say each body part word aloud and ask your child to point to it on the picture or on themselves."
    return instructions, f'<div class="body-parts-row"><div class="coloring-box">{svg}</div><div class="legend">{legend}</div></div>'


