def shape_svg(name, color, size=90):
    path = SHAPE_PATHS.get(name, SHAPE_PATHS["circle"]).format(c=color)
    return f'<svg viewBox="0 0 120 120" width="{size}" height="{size}">{path}</svg>'


def pick_shapes(avoid_titles, n):
    """Pick n shapes not recently referenced by name in avoid_titles, cycling through the set."""
    avoid_text = " ".join(avoid_titles).lower()
    pool = [s for s in SHAPE_NAMES if s not in avoid_text] or SHAPE_NAMES
    random.shuffle(pool)
    return (pool * ((n // len(pool)) + 1))[:n]


# ---------------------------------------------------------------------------
# Difficulty: age-aware baseline + feedback nudge
# ---------------------------------------------------------------------------

DIFFICULTY_LEVELS = ["easy", "medium", "hard"]

AGE_BASE_DIFFICULTY = {
    "Toddlers 1-2 years": "easy",
    "Toddlers 2-3 years": "easy",
    "Preschool 3-4 years": "medium",
    "Pre-K 4-5 years": "medium",
}


def difficulty_for(age_group: str, feedback_text: str) -> str:
    """Starts from an age-appropriate baseline, then nudges one step up/down
    based on the educator's free-text feedback (keyword heuristic — no LLM
    call needed, so it's fast and always available)."""
    base = AGE_BASE_DIFFICULTY.get(age_group, "easy")
    idx = DIFFICULTY_LEVELS.index(base)

    if feedback_text:
        t = feedback_text.lower()
        if "too easy" in t or "harder" in t or "more difficult" in t or "more challenging" in t:
            idx = min(idx + 1, len(DIFFICULTY_LEVELS) - 1)
        elif "too hard" in t or "too difficult" in t or "easier" in t or "simplify" in t:
            idx = max(idx - 1, 0)

    return DIFFICULTY_LEVELS[idx]


def _next_difficulty(difficulty: str) -> str:
    idx = DIFFICULTY_LEVELS.index(difficulty)
    return DIFFICULTY_LEVELS[min(idx + 1, len(DIFFICULTY_LEVELS) - 1)]


