"""
worksheet_generator.py

Weekly worksheet generator for EngageKids AI — VISUAL worksheets, not
paragraphs of instructions.

v3 changes (from v2), driven by:
  - "Developmental milestones and the EYLF/NQS" (Community Child Care
    Co-operative Ltd, EYLF Practice Based Resources) — the educator's own
    reference document, and
  - direct feedback that 1-3y had too few activity types, that a worksheet
    should never be "draw one circle" and stop, and that hollow/outline
    letters are a good example of a stretch task for the 3-4y band.

  1. Age bands are now FIVE groups instead of three, matching the doc's own
     breakpoints where the doc gives them (0-4mo/4-8mo/8-12mo collapsed
     into one "Babies 0-1" band; 1-2y and 2-3y are the doc's own bands).
     The doc's "3 to 5 years" section is NOT split by the source — we
     split it ourselves into "Preschool 3-4" and "Pre-K 4-5" by reading
     which named skills are earlier vs later within that one section
     (tripod grasp / cutting paper / imitating shapes -> 3-4; "may write
     some numbers and letters" / "counts five to ten things" -> 4-5).
     That split is our own interpolation, not a line the document states.
  2. Babies 0-1 years gets NO worksheet. The doc's 0-12mo milestones are
     entirely pre-mark-making (tracks objects, reaches/grasps, points to
     communicate only emerges at 8-12mo) so instead the app produces
     "Look & Point" cards — one big high-contrast shape for the educator
     to hold up and narrate. These are not something the baby completes.
  3. Every other age band has 4-7 age-appropriate categories now (was as
     few as 2 for 1-3y in v2), each tagged to the specific milestone line
     that justifies it — see the comments on CATEGORY_DEFS.
  4. Every worksheet now has a base task PLUS an optional "bonus/stretch"
     section one difficulty step up, generated by the same renderer, so a
     worksheet is never a single static item (the "not just one circle"
     requirement). Non-tiered types (coloring pages, point-and-name cards,
     look & point cards, free scribble) are single-page by nature and are
     not stretched.
  5. New renderers grounded directly in specific milestone lines:
       - look_point            (0-1y: tracks contrast/patterns/faces)
       - point_and_name_shapes (1-2y/2-3y: "points to objects when named",
                                 "recognises...by pointing")
       - point_and_name_body   (1-2y: "knows some body parts",
                                 "points to body parts in a game")
       - first_scribbles       (1-2y: "scribbles with pencil or crayon
                                 held in fist" — free mark-making, not a
                                 precise trace)
       - big_trace             (2-3y/3-4y: "uses a pencil to draw or
                                 scribble in circles and lines",
                                 "imitates variety of shapes in drawing")
       - count_aloud           (2-3y: "begins to count with numbers" —
                                 verbal only, no writing skill yet)
       - hollow_letter_fill    (3-4y: early letter-shape work ahead of
                                 full writing — outline letters to color
                                 in, a stepping stone before "copies
                                 letters" / "writes some letters" at 4-5y)
  6. Difficulty baselines are per-band again (was per-3-band before).
  7. Worksheets-per-week is still educator-configurable; Babies 0-1 uses
     the same setting but for "cards" rather than worksheets.

The page a child sees is still built directly in code as colorful SVG
shapes/figures arranged in a grid — never LLM-written prose. This
guarantees every worksheet is genuinely visual/colorful and low-text,
regardless of what the educator typed in (or didn't type in).

The AI (Groq) is used ONLY for a short title + one-line educator tip, and
that call is optional — if it fails for any reason, a deterministic title
is used instead, so the worksheet never depends on the AI writing well.
"""

