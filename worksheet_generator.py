def get_week_key(d: datetime.date = None) -> str:
    d = d or datetime.date.today()
    iso = d.isocalendar()
    return f"{iso[0]}-W{iso[1]:02d}"


def get_week_index(d: datetime.date = None) -> int:
    d = d or datetime.date.today()
    return (d - datetime.date(2020, 1, 6)).days // 7


def get_categories_for_week(week_index: int, age_group: str, n: int = 3) -> list:
    """Returns n category names appropriate for age_group, rotating through
    that age group's available categories so that, across consecutive
    weeks, every developmental DOMAIN gets covered rather than just
    whichever categories happen to come up first.

    n can exceed the number of distinct categories available for a young
    age group — in that case categories simply repeat within the week,
    which is fine since the shapes/colors/body-parts/letters chosen are
    still randomized per worksheet, and each repeat also gets its own
    bonus/stretch section (see render_with_bonus).
    """
    available = categories_for_age(age_group)
    if not available:
        available = CATEGORY_DEFS  # fallback safety net

    # Order by domain first so consecutive picks favour domain variety,
    # then rotate the start point by week so different weeks lead with
    # different domains too.
    by_domain = sorted(available, key=lambda c: c["domain"])
    pool_len = len(by_domain)
    start = (week_index * n) % pool_len
    picks = [by_domain[(start + i) % pool_len] for i in range(n)]
    return [c["name"] for c in picks]


def render_with_bonus(renderer_key: str, avoid_titles: list, difficulty: str):
    """Runs the base renderer at `difficulty`, then — for renderer types
    that can scale (grids, counts, tracing sets, etc.) — appends an
    optional bonus section one difficulty step up, so a worksheet is never
    a single static item. Card/coloring/free-scribble types are single-page
    by nature and are returned as-is."""
    instructions, body_html = RENDERERS[renderer_key](avoid_titles, difficulty)

    if renderer_key in NON_TIERED_RENDERERS:
        return instructions, body_html

    bonus_difficulty = _next_difficulty(difficulty)
    if bonus_difficulty == difficulty:
        return instructions, body_html

    bonus_instructions, bonus_html = RENDERERS[renderer_key](avoid_titles, bonus_difficulty)
    combined = (
        f'{body_html}'
        f'<div class="bonus-box">'
        f'<div class="bonus-label">⭐ Extra challenge (optional):</div>'
        f'<div class="instructions">{bonus_instructions}</div>'
        f'{bonus_html}'
        f'</div>'
    )
    return instructions, combined


def _maybe_get_ai_title(client, category, age_group, theme, fallback_title):
    """Optional: ask the AI for a fun 3-6 word title. If this fails for any
    reason (rate limit, network, bad response) we silently keep the
    deterministic fallback — the worksheet never depends on this working."""
    try:
        prompt = f"Give ONE fun, short (3-6 word) worksheet title for a {age_group} '{category}' activity" + (f" themed around '{theme}'" if theme else "") + ". Reply with ONLY the title, nothing else."
        resp = client.chat.completions.create(
            model="llama-3.3-70b-versatile",
            messages=[{"role": "user", "content": prompt}],
            max_tokens=20,
        )
        title = resp.choices[0].message.content.strip().strip('"')
        return title if 2 <= len(title) <= 60 else fallback_title
    except Exception:
        return fallback_title


def generate_worksheet(client, age_group: str, category: str, theme: str, avoid_topics: list, feedback_text: str) -> dict:
    cat_def = CATEGORY_BY_NAME.get(category)
    renderer_key = cat_def["renderer"] if cat_def else "coloring"
    domain = cat_def["domain"] if cat_def else DOMAIN_SENSORY
    difficulty = difficulty_for(age_group, feedback_text)
    instructions, body_html = render_with_bonus(renderer_key, avoid_topics, difficulty)

    fallback_title = CATEGORY_TITLES.get(renderer_key, "Worksheet")
    title = _maybe_get_ai_title(client, category, age_group, theme, fallback_title) if client else fallback_title

    html = _render_worksheet_html(title, category, age_group, domain, instructions, body_html)
    return {"title": title, "html": html, "category": category, "domain": domain}


